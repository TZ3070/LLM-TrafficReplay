const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe', headless:true });
  const page = await browser.newPage({ viewport:{ width:1440, height:1120 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(() => {
    window.replayLabels = [];
    const original = CanvasRenderingContext2D.prototype.fillText;
    CanvasRenderingContext2D.prototype.fillText = function (text, ...args) {
      if (this.canvas.closest('.replay-panel')) window.replayLabels.push({ text:String(text), y:args[1] });
      return original.call(this, text, ...args);
    };
  });
  await page.goto('http://127.0.0.1:4173/');
  await page.waitForTimeout(300);
  const bounds = await page.locator('.load-chart').first().boundingBox();
  await page.mouse.move(bounds.x + bounds.width * .3, bounds.y + 100);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width * .7, bounds.y + 100, { steps:8 });
  await page.mouse.up();
  await page.getByRole('button', { name:'确认回放', exact:true }).click();
  await page.getByRole('button', { name:'开始回放', exact:true }).click();
  await page.getByText('回放中', { exact:true }).waitFor();
  await page.waitForTimeout(200);
  await page.evaluate(() => window.replayLabels = []);
  await page.locator('.relative input').check();
  await page.waitForTimeout(200);
  const labels = await page.evaluate(() => window.replayLabels.filter(p => /^\d+ s$/.test(p.text)));
  const unique = [...new Set(labels.map(p => p.text))];
  assert(unique.includes('0 s'), 'relative axis must start at zero');
  assert(unique.length >= 4, 'short replay must show distinct second ticks');
  assert(!labels.some(p => p.text === '0 min'));
  const replay = await page.locator('.replay-panel .load-chart').boundingBox();
  await page.mouse.move(replay.x + replay.width * .55, replay.y + 110);
  await page.waitForTimeout(200);
  assert((await page.locator('.replay-panel').innerText()).includes('回放 +'), 'relative tooltip must show elapsed time');
  await page.evaluate(() => window.replayLabels = []);
  await page.locator('.relative input').uncheck();
  await page.waitForTimeout(200);
  const absolute = await page.evaluate(() => window.replayLabels.map(p => p.text));
  assert(absolute.some(label => /^\d{2}:\d{2}$/.test(label)), 'unchecking must restore absolute times');
  assert.deepEqual(errors, []);
  console.log('PASS: distinct elapsed ticks ' + unique.join(', ') + '; tooltip timestamp conversion; return to absolute time; no runtime errors.');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
